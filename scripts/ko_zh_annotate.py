def translate(word: str):
    """整词（WHOLE / SPECIFIC）优先；否则按「最长的通用后缀」拆分：前缀（专名/韩文原样）+ 后缀中文。"""
    if word in WHOLE:
        return WHOLE[word]
    if word in SPECIFIC:
        return SPECIFIC[word]
    for cut in range(1, len(word)):
        suf = word[cut:]
        if suf in SUFFIX:
            pre = word[:cut]
            return SPECIFIC.get(pre, pre) + SUFFIX[suf]
    return None


def main():
    src = open(PATH, encoding='utf-8').read()
    # 去掉已有的「半角括号 + 中文」注释，避免和全角加注重复
    src = re.sub(r'\(([^)]*[一-鿿][^)]*)\)', '', src)

    words = sorted(set(re.findall(r'[가-힣][가-힣0-9]*', src)), key=len, reverse=True)
    tokens = []
    missing = []
    text = src
    for w in words:
        zh = translate(w)
        if not zh:
            missing.append(w)
            continue
        text = text.replace(w, f'\x00{len(tokens)}\x00')
        tokens.append(f'{w}（{zh}）')
    text = re.sub(r'\x00(\d+)\x00', lambda m: tokens[int(m.group(1))], text)

    if '--dry' in sys.argv:
        print('未命中（需补映射）：')
        for w in sorted(missing):
            print(' ', w)
        return
    open(PATH, 'w', encoding='utf-8').write(text)
    print(f'已加注 {len(tokens)} 个词，未命中 {len(missing)} 个：')
    for w in sorted(missing):
        print(' ', w)


if __name__ == '__main__':
    main()
