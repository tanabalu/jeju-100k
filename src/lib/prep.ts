/**
 * 条目文案归一化：用于「清单里是不是已经有这一条」的去重判断。
 * 去掉所有空白（`\s` 已含全角空格）并忽略大小写，
 * 避免「带 备用袜」和「带备用袜」被当成两条。
 */
export function normItemText(s: string): string {
  return s.replace(/\s+/g, '').toLowerCase()
}

